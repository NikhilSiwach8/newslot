"""Export frontend data for Infernal Kingdom.

Writes into web-sdk/apps/infernal_kingdom/src:
  game/config.ts                 bet modes, symbols and paytable (from game_config.py)
  stories/data/<mode>_books.ts   real books per mode for Storybook, picked to cover features

    cd math-sdk && env/bin/python games/infernal_kingdom/tools/export_frontend.py [--config-only]
"""

import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
from game_config import GameConfig  # noqa: E402

LIBRARY = os.path.join(HERE, "..", "library")
APP_SRC = os.path.realpath(os.path.join(os.path.realpath(os.path.join(HERE, "..")), "..", "..", "web-sdk", "apps", "infernal_kingdom", "src"))
MAX_SCAN = 30000
HEADER = "// Generated by math/infernal_kingdom/tools/export_frontend.py - do not edit by hand.\n"

# Feature tags a book can show; each mode keeps a few books per tag plus plain ones.
def tags(book):
    t = {e["type"] for e in book["events"]}
    kinds = {e.get("kind") for e in book["events"] if e["type"] == "specialResolve"}
    out = set()
    for event, tag in [("infernalTakeover", "takeover"), ("soulApocalypse", "apocalypse"), ("wincap", "wincap"),
                       ("sealPattern", "pattern"), ("instantWin", "harvest"), ("soulMilestone", "milestone"),
                       ("globalMult", "globalMult")]:
        if event in t:
            out.add(tag)
    for k in ("wildBomb", "goldenWildBomb", "split", "overlord"):
        if k in kinds:
            out.add(k)
    if any(e["type"] == "freeSpinTrigger" and e.get("retrigger") for e in book["events"]):
        out.add("retrigger")
    return out


PER_TAG = {"takeover": 2, "apocalypse": 2, "wincap": 1, "pattern": 2, "harvest": 1, "milestone": 1, "globalMult": 1,
           "wildBomb": 2, "goldenWildBomb": 1, "split": 1, "overlord": 1, "retrigger": 1}
PLAIN = {"base": {"basegame": 8, "0": 3, "hellfire": 2, "covenant": 1, "abyssal": 1, "furnace": 1}}


def read_books(mode):
    import zstandard
    path = os.path.join(LIBRARY, "publish_files", f"books_{mode}.jsonl.zst")
    with open(path, "rb") as f:
        reader = io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(f), encoding="utf-8")
        for line in reader:
            yield json.loads(line)


def pick_books(mode):
    plain = dict(PLAIN.get("base" if mode.startswith("base") else "buy", {}))
    want = dict(PER_TAG)
    picked, ids = [], set()
    for n, book in enumerate(read_books(mode)):
        if n >= MAX_SCAN:
            break
        bt = tags(book)
        take = [t for t in bt if want.get(t, 0) > 0]
        if take or plain.get(book["criteria"], 0) > 0:
            for t in take:
                want[t] -= 1
            if not take:
                plain[book["criteria"]] -= 1
            if book["id"] not in ids:
                ids.add(book["id"])
                book["tags"] = sorted(bt)
                picked.append(book)
        if not any(want.values()) and not any(plain.values()):
            break
    if mode.startswith("base") is False and len(picked) < 6:
        for book in read_books(mode):
            if book["id"] not in ids and book["criteria"] != "wincap":
                book["tags"] = sorted(tags(book))
                picked.append(book)
                ids.add(book["id"])
            if len(picked) >= 6:
                break
    return picked


def export_config(config):
    symbols = {}
    for (kind, sym), pay in sorted(config.paytable.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        symbols.setdefault(sym, {"paytable": []})["paytable"].append({str(kind): pay})
    for prop, names in config.special_symbols.items():
        for n in names:
            symbols.setdefault(n, {"paytable": None})
            symbols[n].setdefault("special_properties", []).append(prop)
    out = {
        "providerName": "infernal",
        "gameName": "Infernal Kingdom",
        "gameID": config.game_id,
        "rtp": config.rtp,
        "numReels": config.num_reels,
        "numRows": config.num_rows,
        "wincap": config.wincap,
        "betModes": {bm.get_name(): {"cost": bm.get_cost(), "feature": bm.get_feature(), "buyBonus": bm.get_buybonus(),
                                     "rtp": bm.get_rtp(), "max_win": bm.get_wincap()} for bm in config.bet_modes},
        "symbols": dict(sorted(symbols.items())),
        "paddingReels": {"basegame": [], "freegame": []},
    }
    with open(os.path.join(APP_SRC, "game", "config.ts"), "w", encoding="utf-8") as f:
        f.write(HEADER + "export default " + json.dumps(out, indent="\t") + ";\n")


if __name__ == "__main__":
    config = GameConfig()
    export_config(config)
    print("wrote", os.path.join(APP_SRC, "game", "config.ts"))
    if "--config-only" in sys.argv:
        sys.exit(0)
    os.makedirs(os.path.join(APP_SRC, "stories", "data"), exist_ok=True)
    for bm in config.bet_modes:
        mode = bm.get_name()
        if not os.path.exists(os.path.join(LIBRARY, "publish_files", f"books_{mode}.jsonl.zst")):
            print(f"{mode}: not simulated yet, skipped")
            continue
        books = pick_books(mode)
        out = os.path.join(APP_SRC, "stories", "data", f"{mode}_books.ts")
        with open(out, "w", encoding="utf-8") as f:
            f.write(HEADER + "export default " + json.dumps(books, separators=(",", ":")) + ";\n")
        seen = sorted({t for b in books for t in b["tags"]})
        print(f"{mode}: {len(books)} books, {os.path.getsize(out) / 1024:.0f} KB, tags {seen}")
