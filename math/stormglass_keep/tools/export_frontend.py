"""Export frontend data from the generated math library.

Writes into the web app (web-sdk/apps/stormglass_keep/src):
  game/config.ts                 symbol/bet-mode config used for typing and the paytable
  stories/data/<mode>_books.ts   a small, varied sample of real books per mode for Storybook

Run with the Math SDK environment after `make run GAME=stormglass_keep`:

    math-sdk/env/bin/python math/stormglass_keep/tools/export_frontend.py
"""

import io
import json
import os

import zstandard

HERE = os.path.dirname(os.path.abspath(__file__))
LIBRARY = os.path.join(HERE, "..", "library")
APP_SRC = os.path.join(HERE, "..", "..", "..", "web-sdk", "apps", "stormglass_keep", "src")
BEAM_EVENTS = {"beamClear", "beamWilds", "beamSurge"}
MAX_SCAN = 20000

# books to keep per criteria, per mode: (plain books, books that fire a beam stage)
PICKS = {
    "base": {"basegame": (14, 8), "0": (4, 0), "watch": (2, 1), "eye": (1, 1), "drowned": (1, 0), "wincap": (1, 0)},
    "surge": {"basegame": (6, 2), "0": (2, 0), "watch": (2, 1), "eye": (1, 0), "drowned": (1, 0)},
    "beam": {"basegame": (8, 8), "0": (3, 0), "wincap": (1, 0)},
    "bonus": {"watch": (3, 3), "wincap": (1, 0)},
    "super": {"eye": (2, 3), "wincap": (1, 0)},
    "mystery": {"nobonus": (8, 2), "eye": (1, 2), "drowned": (1, 2)},
}


def read_books(mode):
    path = os.path.join(LIBRARY, "publish_files", f"books_{mode}.jsonl.zst")
    with open(path, "rb") as f:
        reader = io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(f), encoding="utf-8")
        for line in reader:
            yield json.loads(line)


def pick_books(mode):
    wanted = {crit: list(counts) for crit, counts in PICKS[mode].items()}
    picked = []
    for scanned, book in enumerate(read_books(mode)):
        if scanned >= MAX_SCAN or not any(a or b for a, b in wanted.values()):
            break
        remaining = wanted.get(book["criteria"])
        if remaining is None:
            continue
        has_beam = any(e["type"] in BEAM_EVENTS for e in book["events"])
        slot = 1 if has_beam and remaining[1] > 0 else 0
        if remaining[slot] > 0:
            remaining[slot] -= 1
            picked.append(book)
    return picked


def write_ts(path, value):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by math/stormglass_keep/tools/export_frontend.py - do not edit by hand.\n")
        f.write("export default " + json.dumps(value, separators=(",", ":")) + ";\n")


def export_config():
    with open(os.path.join(LIBRARY, "configs", "config_fe_stormglass_keep.json"), encoding="utf-8") as f:
        config = json.load(f)
    symbols = {}
    for entry in config["symbols"]:
        symbols.update(entry)
    config["symbols"] = dict(sorted(symbols.items()))
    config["providerName"] = "stormglass"
    config["gameName"] = "Stormglass Keep"
    config["paddingReels"] = {"basegame": [], "freegame": []}
    with open(os.path.join(APP_SRC, "game", "config.ts"), "w", encoding="utf-8") as f:
        f.write("// Generated by math/stormglass_keep/tools/export_frontend.py - do not edit by hand.\n")
        f.write("export default " + json.dumps(config, indent="\t") + ";\n")


if __name__ == "__main__":
    export_config()
    os.makedirs(os.path.join(APP_SRC, "stories", "data"), exist_ok=True)
    for mode_name in PICKS:
        books = pick_books(mode_name)
        out = os.path.join(APP_SRC, "stories", "data", f"{mode_name}_books.ts")
        write_ts(out, books)
        summary = {}
        for b in books:
            summary[b["criteria"]] = summary.get(b["criteria"], 0) + 1
        print(f"{mode_name}: {len(books)} books {summary} -> {os.path.getsize(out) / 1024:.0f} KB")
